import assert from 'node:assert/strict';
import { execFile } from 'node:child_process';
import { mkdtemp, mkdir, readFile, realpath, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { parseArgs, promisify } from 'node:util';
import { digest } from '../packages/workflow-runtime/unified/inventory.mjs';

const { values } = parseArgs({ options: { distribution: { type: 'string' }, 'expected-manifest-sha256': { type: 'string' } } });
assert(values.distribution && values['expected-manifest-sha256']);
const root = await realpath(await mkdtemp(join(tmpdir(), 'temari-unified-recipient-')));
const home = join(root, 'home'), workspace = join(root, 'project'), profile = join(root, 'profile.json');
await mkdir(workspace);
const selection = JSON.stringify({ schema: 1, id: 'recipient-proof', workspaceRoot: workspace, port: 0, transport: { kind: 'ollama', model: 'fixture-not-called' } });
await writeFile(profile, selection);
const exec = promisify(execFile);
const install = async (pin = values['expected-manifest-sha256']) => JSON.parse((await exec(join(values.distribution, 'setup'), ['setup', '--home', home, '--profile', profile, '--expected-manifest-sha256', pin], { env: { ...process.env, PATH: '/usr/bin:/bin' }, timeout: 120000, maxBuffer: 4 * 1024 * 1024 })).stdout);
try {
  const first = await install();
  assert.equal(first.phase, 'ready');
  assert(first.knowledge.citations.length && first.knowledge.mcpReadiness.connected);
  assert.equal(first.knowledge.mcpReadiness.status, 'complete');
  await writeFile(join(home, 'user-note.txt'), 'Retain this user data.');
  const retried = await install();
  assert.equal(retried.knowledge.sourceId, first.knowledge.sourceId);
  assert.equal(await readFile(join(home, 'user-note.txt'), 'utf8'), 'Retain this user data.');
  await assert.rejects(install('0'.repeat(64)), /manifest digest differs/);
  await writeFile(profile, selection + '\n');
  await assert.rejects(install(), /another release or profile/);
  await writeFile(profile, selection);
  const cfgPath = join(home, 'knowledge', 'venv', 'pyvenv.cfg'), cfg = await readFile(cfgPath);
  await writeFile(cfgPath, Buffer.concat([cfg, Buffer.from('\ninclude-system-site-packages = true\n')]));
  await assert.rejects(install(), /environment configuration changed/);
  await writeFile(cfgPath, cfg);
  const site = join(home, 'knowledge', 'venv', 'lib', 'python3.12', 'site-packages');
  const injection = join(site, 'sitecustomize.py'), marker = join(root, 'startup-executed');
  await writeFile(injection, `from pathlib import Path\nPath(${JSON.stringify(marker)}).write_text('executed')\n`);
  await assert.rejects(install(), /Unexpected installed knowledge dependency/);
  await assert.rejects(readFile(marker), { code: 'ENOENT' });
  await rm(injection);
  const dependency = join(site, 'pypdf', '__init__.py'), before = digest(await readFile(dependency));
  await rm(dependency);
  await install();
  assert.equal(digest(await readFile(dependency)), before);
  const python = join(home, 'knowledge', 'venv', 'bin', 'python');
  const sourceCount = await exec(python, ['-I', '-B', '-c', 'import sys; from pathlib import Path; from knowledge_agent.source_registry import SourceRegistry; print(len(SourceRegistry(Path(sys.argv[1])).list()))', join(home, 'knowledge', 'workspace')]);
  assert.equal(sourceCount.stdout.trim(), '1');
  console.log(JSON.stringify({ status: 'PASS', platform: `${process.platform}-${process.arch}`, coldPath: '/usr/bin:/bin', knowledge: 'actual discovery, verified read and MCP handshake', retry: 'data retained; source registration idempotent; partial copy repaired', refused: ['manifest drift', 'profile drift', 'venv config drift', 'startup injection before execution'], model: 'not invoked' }, null, 2));
} finally { await rm(root, { recursive: true, force: true }); }
